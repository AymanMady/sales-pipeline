"""Step 4: load into PostgreSQL.

staging receives the raw CSVs untouched - a trace to fall back on when a
number in the report looks wrong. core receives the clean tables.

Tables are truncated first, so re-running the pipeline never duplicates rows.
"""

import logging

from sqlalchemy import text

from src.db import engine

logger = logging.getLogger(__name__)

# Parents before children, because foreign keys require it
LOAD_ORDER = ["customers", "products", "orders", "order_items"]

COLUMNS = {
    "customers": ["customer_id", "first_name", "last_name", "email",
                  "city", "country", "signup_date"],
    "products": ["product_id", "product_name", "category", "unit_price"],
    "orders": ["order_id", "customer_id", "order_date", "status"],
    # order_item_id and line_total are generated by PostgreSQL
    "order_items": ["order_id", "product_id", "quantity", "unit_price"],
}


def _truncate(schema, tables):
    targets = ", ".join(f"{schema}.{name}" for name in tables)
    with engine.begin() as connection:
        connection.execute(text(f"TRUNCATE {targets} RESTART IDENTITY CASCADE"))


def _insert(connection, name, schema, table):
    table.to_sql(name, connection, schema=schema, if_exists="append",
                 index=False, method="multi", chunksize=1000)
    logger.info("  %s.%-12s %5d rows", schema, name, len(table))


def load_staging(raw):
    _truncate("staging", list(raw))
    with engine.begin() as connection:
        for name, table in raw.items():
            _insert(connection, name, "staging", table)


def load_core(tables):
    # Empty children first, then fill parents first
    _truncate("core", list(reversed(LOAD_ORDER)))
    counts = {}
    with engine.begin() as connection:
        for name in LOAD_ORDER:
            table = tables[name][COLUMNS[name]].copy()
            # psycopg2 cannot serialise pandas' nullable Int64, and by now
            # every missing id has already been dropped
            for column in table.columns:
                if table[column].dtype == "Int64":
                    table[column] = table[column].astype("int64")
            _insert(connection, name, "core", table)
            counts[name] = len(table)
    return counts
